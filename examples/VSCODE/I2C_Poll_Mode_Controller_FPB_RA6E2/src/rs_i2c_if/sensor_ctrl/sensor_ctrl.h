#ifndef RS_SENSOR_CRTL_H_
#define RS_SENSOR_CRTL_H_

#include "hal_data.h"


#if BSP_CFG_RTOS == 2
#include "FreeRTOS.h"
#include "semphr.h"
#endif


/*******************************************************************************************************************//**
 * @brief SRAM objects required by rs_i2c_if_SensorDataRead().
 *
 * Runtime control blocks, mutable configurations, the read context, and the read destination are kept in this object.
 * API tables remain in Flash because they are read-only and do not need to be copied into SRAM.
 **********************************************************************************************************************/
typedef struct st_rs_i2c_if_light_sensor_ctrl
{
    /* RS I2C communications hierarchy (writable copies) */
    rs_i2c_if_instance_t             i2c_instance;
    rs_i2c_if_cfg_t                  i2c_cfg;
    i2c_master_cfg_t                 i2c_hal_cfg;
    rs_i2c_if_bus_extended_cfg_t     i2c_bus_cfg;
    rs_i2c_if_instance_ctrl_t        i2c_ctrl;      /* use your actual RS I2C ctrl type */

    /* ISL76682 hierarchy (writable copies) */
    rm_isl76682_instance_t           light_instance;
    rm_isl76682_cfg_t                light_cfg;
    rm_isl76682_instance_ctrl_t      light_ctrl;
} rs_i2c_if_light_sensor_ctrl_t;


/** @brief Generates the configurations required for sensor control. */
fsp_err_t rs_i2c_if_LightSensorConfigGen (
    rs_i2c_if_instance_t const         * const p_src_comms_instance,
    rm_isl76682_instance_t const       * const p_src_light_instance,
    rs_i2c_if_light_sensor_ctrl_t      * const p_dst);

/** @brief Checks the configurations required for sensor control. */
fsp_err_t rs_i2c_if_LightSensorConfigCheck (
    rs_i2c_if_instance_t const              * const p_src_comms_instance,
    rm_isl76682_instance_t const            * const p_src_light_instance,
    rs_i2c_if_light_sensor_ctrl_t const     * const p_dst);

/* @brief Handles the external interrupt generated by the sensor. */


#endif /* RS_SENSOR_CRTL_H_ */
